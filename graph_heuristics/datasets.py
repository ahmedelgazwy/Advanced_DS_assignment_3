"""The BHOSLIB/FRB benchmark graphs: catalogue, exact optima, download and loading.

The 36 graphs come from the BHOSLIB collection of Network Repository
[Rossi & Ahmed 2015], https://networkrepository.com/bhoslib.php. Instance
``frbN-K-i`` was generated by Model RB [Xu et al. 2007]: N groups of K
vertices, vertex ``g*K + j`` (0-based) in group g, with a planted solution.

Each graph is used in two forms (docs/theory.md, section 6):

* ``clq``, as published (dense). The groups are independent sets and the
  planted solution is an N-clique, so the chromatic number is exactly N.
* ``mis``, the complement (sparse). The groups are cliques and the planted
  solution is an independent set of size N, so the minimum vertex cover has
  exactly N*K - N vertices.

AI-assisted: generated with Claude Code; reviewed and tested by Ahmed Elgazwy
(see README, "AI usage and authorship").
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

from graph_heuristics.graph import Graph
from graph_heuristics.graph_io import read_mtx

#: Where the zip files and manifest.json live.
DATA_DIR = Path(__file__).resolve().parent.parent / "data"
#: Download location of ``<name>.zip`` on Network Repository.
BASE_URL = "https://nrvis.com/download/data/bhoslib/"
#: The landing page of the collection (cited in the report).
SOURCE_PAGE = "https://networkrepository.com/bhoslib.php"
#: The two forms of each graph.
FORMS = ("clq", "mis")

#: The families on Network Repository, smallest first (frb56-25 is not there).
FAMILIES = ("frb30-15", "frb35-17", "frb40-19", "frb45-21", "frb50-23", "frb53-24", "frb59-26")
#: All 36 instance names: five per family, plus frb100-40.
INSTANCE_NAMES = tuple(f"{family}-{i}" for family in FAMILIES for i in range(1, 6)) + (
    "frb100-40",
)

_NAME = re.compile(r"^frb(\d+)-(\d+)(?:-(\d+))?$")


@dataclass(frozen=True)
class FrbInstance:
    """One FRB graph and its exact optima.

    Attributes:
        name: Instance name, e.g. ``frb30-15-1``.
        groups: N, the number of groups.
        group_size: K, the vertices per group.
    """

    name: str
    groups: int
    group_size: int

    @property
    def family(self) -> str:
        """The family name, e.g. ``frb30-15``."""
        return f"frb{self.groups}-{self.group_size}"

    @property
    def n(self) -> int:
        """Number of vertices, N * K."""
        return self.groups * self.group_size

    @property
    def chromatic_number(self) -> int:
        """Exact chromatic number of the ``clq`` form: N."""
        return self.groups

    @property
    def min_vertex_cover(self) -> int:
        """Exact minimum vertex cover of the ``mis`` form: N*K - N."""
        return self.n - self.groups

    @property
    def url(self) -> str:
        """Download URL of the zip file."""
        return f"{BASE_URL}{self.name}.zip"

    def zip_path(self, data_dir: Path = DATA_DIR) -> Path:
        """Local path of the zip file.

        Args:
            data_dir: The data folder.

        Returns:
            ``data_dir / "<name>.zip"``.
        """
        return data_dir / f"{self.name}.zip"


def parse_instance(name: str) -> FrbInstance:
    """Make an :class:`FrbInstance` from a name such as ``frb30-15-1``.

    Args:
        name: ``frbN-K`` or ``frbN-K-i``.

    Returns:
        The instance, with N and K read from the name.

    Raises:
        ValueError: If the name does not have that form.
    """
    match = _NAME.match(name)
    if match is None:
        raise ValueError(f"not an FRB instance name: {name!r}")
    return FrbInstance(name, int(match.group(1)), int(match.group(2)))


def frb_instances(families: Optional[list[str]] = None) -> list[FrbInstance]:
    """The FRB instances, smallest first.

    Args:
        families: Keep only these families (e.g. ``["frb30-15"]``); None keeps all 36.

    Returns:
        The instances.
    """
    instances = [parse_instance(name) for name in INSTANCE_NAMES]
    if families is None:
        return instances
    return [inst for inst in instances if inst.family in families]


def load_frb(instance: FrbInstance, form: str = "clq", data_dir: Path = DATA_DIR) -> Graph:
    """Load an FRB graph from its zip file.

    Args:
        instance: The instance.
        form: ``"clq"`` for the graph as published, ``"mis"`` for its complement.
        data_dir: The folder holding the zip files.

    Returns:
        The graph.

    Raises:
        FileNotFoundError: If the zip file is missing (run
            ``python -m scripts.download_dataset``).
        ValueError: If ``form`` is unknown.
    """
    if form not in FORMS:
        raise ValueError(f"form must be one of {FORMS}, got {form!r}")
    path = instance.zip_path(data_dir)
    if not path.exists():
        raise FileNotFoundError(f"{path} is missing: run python -m scripts.download_dataset")
    graph = read_mtx(path)
    return graph if form == "clq" else graph.complement()


def is_available(instance: FrbInstance, data_dir: Path = DATA_DIR) -> bool:
    """Whether the zip file of an instance has been downloaded.

    Args:
        instance: The instance.
        data_dir: The data folder.

    Returns:
        True if the zip file exists.
    """
    return instance.zip_path(data_dir).exists()


def groups_are_independent(graph: Graph, group_size: int) -> bool:
    """Check the FRB group structure: no edge joins two vertices of the same group.

    Args:
        graph: An FRB graph in ``clq`` form.
        group_size: K.

    Returns:
        True if every block ``g*K .. g*K + K - 1`` is an independent set.
    """
    return all(u // group_size != v // group_size for u, v in graph.edges())


def sha256_of(path: Path) -> str:
    """The SHA-256 checksum of a file, as hex.

    Args:
        path: The file.

    Returns:
        64 hex digits.
    """
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def load_manifest(data_dir: Path = DATA_DIR) -> dict:
    """Read ``manifest.json``: sizes, edge counts and checksums of every instance.

    Args:
        data_dir: The data folder.

    Returns:
        The parsed manifest, or an empty dict if the file does not exist.
    """
    path = data_dir / "manifest.json"
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))
